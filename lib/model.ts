// Token Radar's model (radar-2): a comps-calibrated implied value for every protocol
// that records no token, ranked for the board; the protocols that already trade are
// kept apart and shown with the market's own values, never mixed into the ranking.
//
// The board covers the snapshot's whole watchlist (the floor, never the ceiling) and
// every other pre-token protocol that passes the watchlist's own exclusion rule
// without its $50M floor: no CEX, no bridge, no liquid staking or restaking, no
// versioned pool, no wrapped or staked product, no exchange-branded product. The
// rule is the house's, applied to the whole snapshot; no protocol name is ever
// special-cased, and the same function scores every row.
//
// Implied value follows only from the snapshot's own figures:
//
//   comp     = the category's median FDV/TVL among the snapshot's live-token
//              protocols (at least 3 of them), else the whole market's median,
//              clamped to [0.02, 1.00]          -- what the market pays per $ of TVL
//   base     = tvl_usd x comp
//   growth   = clamp(change_7d, -60, 120) per cent
//   growthM  = 1 + (growth / 100) x 0.5
//   maturity = 0.70 + min(age_days, 1095) / 1095 x 0.30   (age unknown: 365 days)
//   breadth  = 1 + min(chains - 1, 9) x 0.01             -- one chain is the base
//   implied  = max(1, round(base x growthM x maturity x breadth))
//
// A protocol that records no token is not claimed to have none: the snapshot is
// DefiLlama's record, and a token it does not carry may still exist. The board
// ranks what the record shows, and the dashboard says so on every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
